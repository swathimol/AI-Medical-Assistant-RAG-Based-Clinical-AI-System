"""AI Medical Assistant - RAG system (educational use only).

Run:  streamlit run app.py
Knowledge files (.txt / .md) live in the ./data folder.

Optional settings (environment variables or Streamlit secrets):
  ANTHROPIC_API_KEY   use Claude for answers
  ENABLE_LOCAL_LLM    1 (default) / 0  - local Flan-T5 when no key
  USE_RERANKER        0 (default) / 1  - cross-encoder reranking
  EMBED_MODEL         default all-MiniLM-L6-v2
  MIN_SIM             evidence threshold (cosine), default 0.30
"""
import os
import streamlit as st
from rag_core import (RAG, generate, DISCLAIMER, EMERGENCY_WORDS, NO_EVIDENCE,
                      DEFAULT_EMBED, DEFAULT_RERANKER)


def setting(name, default=""):
    """Read from Streamlit secrets (cloud) first, then environment."""
    try:
        if name in st.secrets:
            return str(st.secrets[name])
    except Exception:
        pass
    return os.getenv(name, default)


EMBED_MODEL = setting("EMBED_MODEL", DEFAULT_EMBED)
USE_RERANKER = setting("USE_RERANKER", "0") == "1"
MIN_SIM = float(setting("MIN_SIM", "0.30"))
USE_LOCAL = setting("ENABLE_LOCAL_LLM", "1") == "1"
API_KEY = setting("ANTHROPIC_API_KEY") or None
TOP_K = 4

MODE_LABEL = {
    "claude": "Answer (generated by Claude from retrieved documents):",
    "local": "Answer (generated locally from retrieved documents):",
    "extractive": "Answer (extracted from the knowledge base):",
}


@st.cache_resource(show_spinner="Building knowledge base...")
def load_rag(embed_model, use_reranker):
    return RAG(embed_model=embed_model,
               reranker=DEFAULT_RERANKER if use_reranker else None)


st.set_page_config(page_title="AI Medical Assistant", page_icon="🩺")
st.title("🩺 AI Medical Assistant (RAG)")
st.warning(DISCLAIMER)

rag = load_rag(EMBED_MODEL, USE_RERANKER)
if not rag.chunks:
    st.error("No documents found. Add .txt/.md files to the 'data' folder and restart.")
    st.stop()

st.sidebar.write(f"Knowledge base: {len(set(rag.sources))} files, {len(rag.chunks)} chunks")
st.sidebar.caption(f"Vector index: FAISS | Embeddings: {EMBED_MODEL}")
st.sidebar.caption(f"Reranker: {'on' if USE_RERANKER else 'off'} | Evidence threshold: {MIN_SIM}")

query = st.text_input("Ask a clinical question:")
if query:
    if any(w in query.lower() for w in EMERGENCY_WORDS):
        st.error("This may be an emergency. Seek immediate medical care.")
    hits, top_sim = rag.retrieve(query, k=TOP_K)
    if top_sim < MIN_SIM:
        st.info(NO_EVIDENCE)
    else:
        with st.spinner("Generating answer..."):
            text, mode, err = generate(rag, query, hits, api_key=API_KEY,
                                       use_local=USE_LOCAL)
        if err:
            st.caption(err)
        st.success(MODE_LABEL[mode])
        st.markdown(text)
    with st.expander("Retrieved sources"):
        for i, h in enumerate(hits):
            st.markdown(f"**[{i+1}] {h['source']}** (similarity {h['sim']:.2f}"
                        + (f", rerank score {h['score']:.2f}" if USE_RERANKER else "") + ")")
            st.caption(h["text"])
